#!/usr/bin/env node
/**
 * Writes the app version files configure reads through `--with-version-file-path`
 * (configs/common/mozconfig, spec m0-app-version):
 *   version.txt         surfer.json version.version (the Firefox version) -> MOZ_APP_VERSION,
 *                       appinfo.version
 *   version_display.txt brands.<brand>.release.displayVersion (Vimma's) -> MOZ_APP_VERSION_DISPLAY,
 *                       `vimma --version`, the About dialog
 * into src/browser/config/vimma/ (git-ignored); `surfer import` links them into the engine.
 * Usage: node tools/version-files/version-files.mjs [brand]   (default brand: vimma)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** A Firefox version as configure parses it: x.y or x.y.z, optionally a beta (`bN`). */
const FIREFOX = /^\d+\.\d+(?:\.\d+)?(?:[ab]\d+)?$/;
/** SemVer with an optional pre-release (plan §7: `0.x.y`, nightlies `0.x.y-nightly.<date>`). */
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

/** configure reads only the last line (as with config/milestone.txt), so the header is free. */
const HEADER = [
  "# This Source Code Form is subject to the terms of the Mozilla Public",
  "# License, v. 2.0. If a copy of the MPL was not distributed with this",
  "# file, You can obtain one at http://mozilla.org/MPL/2.0/.",
  "# Generated by tools/version-files/version-files.mjs from surfer.json; do not edit.",
  "",
].join("\n");

/**
 * @typedef {{ version?: { version?: unknown },
 *   brands?: Record<string, { release?: { displayVersion?: unknown } }> }} SurferConfig
 */

/**
 * @param {SurferConfig} config parsed surfer.json
 * @param {string} [brand]
 * @returns {{ "version.txt": string, "version_display.txt": string }}
 */
export function versionFiles(config, brand = "vimma") {
  const firefox = config.version?.version;
  if (typeof firefox !== "string" || !FIREFOX.test(firefox)) {
    throw new Error(`surfer.json version.version is not a Firefox version: ${String(firefox)}`);
  }
  const branding = config.brands?.[brand];
  if (!branding) throw new Error(`surfer.json has no brands.${brand}`);
  const display = branding.release?.displayVersion;
  if (typeof display !== "string" || !SEMVER.test(display)) {
    throw new Error(
      `surfer.json brands.${brand}.release.displayVersion is not SemVer: ${String(display)}`,
    );
  }
  return {
    "version.txt": `${HEADER}${firefox}\n`,
    "version_display.txt": `${HEADER}${display}\n`,
  };
}

/**
 * @param {SurferConfig} config
 * @param {string} dir created if missing
 * @param {string} [brand]
 * @returns {{ firefox: string, display: string }} the versions written
 */
export function writeVersionFiles(config, dir, brand) {
  const files = versionFiles(config, brand);
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(dir, name), content);
  /** @param {string} file */
  const version = (file) => file.trimEnd().split("\n").at(-1) ?? "";
  return { firefox: version(files["version.txt"]), display: version(files["version_display.txt"]) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("../../", import.meta.url);
  const config = JSON.parse(readFileSync(new URL("surfer.json", root), "utf8"));
  const dir = fileURLToPath(new URL("src/browser/config/vimma/", root));
  const { firefox, display } = writeVersionFiles(config, dir, process.argv[2]);
  console.log(`version-files: ${firefox} (Firefox), ${display} (display) -> ${dir}`);
}
